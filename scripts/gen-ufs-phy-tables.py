#!/usr/bin/env python3
"""Generate the SM8250 UFS PHY init tables from the Linux QMP driver.

The SM8250 QMP UFS PHY uses the SM8150 base tables with the SM8250 HS-G4
overlays; the UFS driver's cfgs are copied here as plain (offset, value) pairs
so the UEFI PlatformUfsLib can replay them without the Linux headers.
"""
import base64
import re
import urllib.request
from pathlib import Path

BASE = 'https://kernel.googlesource.com/pub/scm/linux/kernel/git/torvalds/linux/+/master/drivers/phy/qualcomm/'
FILES = {
    'qmp-ufs.c': 'phy-qcom-qmp-ufs.c',
    'qserdes-com-v4.h': 'phy-qcom-qmp-qserdes-com-v4.h',
    'qserdes-txrx-v4.h': 'phy-qcom-qmp-qserdes-txrx-v4.h',
    'pcs-ufs-v4.h': 'phy-qcom-qmp-pcs-ufs-v4.h',
}
CACHE = Path('.cache/ufs-phy')
CACHE.mkdir(parents=True, exist_ok=True)


def fetch(name):
    cache = CACHE / name
    if cache.is_file():
        return cache.read_text()
    raw = urllib.request.urlopen(
        urllib.request.Request(BASE + FILES[name] + '?format=TEXT', headers={'User-Agent': 'Mozilla/5.0'}),
        timeout=60).read()
    text = base64.b64decode(raw).decode()
    cache.write_text(text)
    return text

defines = {}
for header in ('qserdes-com-v4.h', 'qserdes-txrx-v4.h', 'pcs-ufs-v4.h'):
    for match in re.finditer(r'#define\s+([A-Z0-9_]+)\s+(0x[0-9a-fA-F]+|\d+)', fetch(header)):
        defines[match.group(1)] = int(match.group(2), 0)

source = fetch('qmp-ufs.c')
tables = {}
for match in re.finditer(r'static const struct qmp_phy_init_tbl\s+(\w+)\[\]\s*=\s*\{(.*?)\};', source, re.S):
    name, body = match.group(1), match.group(2)
    entries = []
    for cfg in re.finditer(r'QMP_PHY_INIT_CFG\(\s*([A-Z0-9_]+)\s*,\s*(0x[0-9a-fA-F]+|\d+)\s*\)', body):
        reg, val = cfg.group(1), int(cfg.group(2), 0)
        if reg not in defines:
            tables[name] = None
            break
        entries.append((defines[reg], val))
    else:
        tables[name] = entries

wanted = [
    ('sm8150_ufsphy_serdes', 'serdes'),
    ('sm8150_ufsphy_tx', 'tx'),
    ('sm8150_ufsphy_rx', 'rx'),
    ('sm8150_ufsphy_pcs', 'pcs'),
    ('sm8150_ufsphy_hs_b_serdes', 'hs_b_serdes'),
    ('sm8250_ufsphy_hs_g4_tx', 'hs_g4_tx'),
    ('sm8250_ufsphy_hs_g4_rx', 'hs_g4_rx'),
    ('sm8150_ufsphy_hs_g4_pcs', 'hs_g4_pcs'),
]
out = ['// SPDX-License-Identifier: GPL-2.0-only',
       '// Generated by scripts/gen-ufs-phy-tables.py from Linux phy-qcom-qmp-ufs.c.',
       '// SM8250 QMP UFS PHY: SM8150 base tables plus the SM8250 HS-G4 overlays.',
       '#pragma once', '#include <stdint.h>', '',
       'struct t970_ufs_phy_reg { uint32_t offset; uint32_t value; };', '']
for table, short in wanted:
    if not tables.get(table):
        raise SystemExit(f'wanted table {table} has unresolved registers')
    out.append(f'static const struct t970_ufs_phy_reg t970_ufs_phy_{short}[] = {{')
    for offset, value in tables[table]:
        out.append(f'  {{ 0x{offset:03x}, 0x{value:04x} }},')
    out.append('};')
    out.append('')
target = Path('package/firmware/Platforms/Samsung/gts7xlwifiPkg/Library/PlatformUfsLib/Sm8250UfsPhyTables.h')
target.parent.mkdir(parents=True, exist_ok=True)
target.write_text('\n'.join(out))
print('wrote', target, 'tables', {short: len(tables[t]) for t, short in wanted})
