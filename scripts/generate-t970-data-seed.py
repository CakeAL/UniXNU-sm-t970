#!/usr/bin/env python3
"""Generate sparse 4 KiB metadata from a host-created, unmounted APFS image."""
import argparse
import errno
import hashlib
import os
from pathlib import Path
import struct

SIZE = 78844506112
UUID = '42888767-E4D4-467C-9FB6-A20A2645B6CC'
EXPECTED = 'de601da2f0e188fc5c3f23ef8c799c17f9f86b9fff851a7b962824db10043902'

p = argparse.ArgumentParser()
p.add_argument('image', type=Path)
p.add_argument('output', type=Path)
a = p.parse_args()
if a.image.stat().st_size != SIZE:
    raise SystemExit('Unexpected image capacity')
fd = os.open(a.image, os.O_RDONLY)
blocks = {}
try:
    first = os.pread(fd, 4096, 0)
    if first[32:36] != b'NXSB' or struct.unpack_from('<I', first, 36)[0] != 4096 or struct.unpack_from('<Q', first, 40)[0] != SIZE // 4096:
        raise SystemExit('Unexpected APFS superblock geometry')
    pos = 0
    while pos < SIZE:
        try:
            start = os.lseek(fd, pos, os.SEEK_DATA)
        except OSError as e:
            if e.errno == errno.ENXIO:
                break
            raise
        end = min(os.lseek(fd, start, os.SEEK_HOLE), SIZE)
        for offset in range(start // 4096 * 4096, end, 4096):
            block = os.pread(fd, 4096, offset)
            if any(block):
                blocks[offset // 4096] = block
        pos = end
finally:
    os.close(fd)
indices = sorted(blocks)
data = b''.join(blocks[i] for i in indices)
if len(indices) != 32 or hashlib.sha256(data).hexdigest() != EXPECTED:
    raise SystemExit('APFS seed differs from the reviewed host image')
lines = ['// Generated by scripts/generate-t970-data-seed.py from the reviewed host-only APFS image.',
         '// Volume UUID ' + UUID + '; image size ' + str(SIZE) + ' bytes.',
         '#pragma once', '#include <stdint.h>', '',
         'static const uint32_t kT970ApfsSeedBlocks = %d;' % len(indices),
         'static const uint32_t kT970ApfsSeedIndex[kT970ApfsSeedBlocks] = {' + ','.join(map(str, indices)) + '};',
         'static const uint8_t kT970ApfsSeedData[] = {']
lines.extend(','.join(map(str, data[i:i+32])) + ',' for i in range(0, len(data), 32))
lines.append('};')
a.output.write_text('\n'.join(lines) + '\n')
